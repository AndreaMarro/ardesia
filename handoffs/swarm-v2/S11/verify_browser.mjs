// Run from repository root; reuses installed Playwright, real HTTP/Core, one browser.
import {createRequire} from 'node:module';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
const require=createRequire(path.resolve('package.json'));
const {chromium}=require('playwright-core');
const [accessFile,output]=process.argv.slice(2);
if(!accessFile||!output)throw new Error('usage: node verify_browser.mjs PRIVATE_ACCESS_JSON OUTPUT_DIR');
const access=JSON.parse(await readFile(accessFile,'utf8'));
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce',acceptDownloads:true});
const base='http://127.0.0.1:55610';
const login=await context.request.post(base+'/study/session',{data:{token:access.studentToken}});
if(!login.ok())throw new Error('login '+login.status());
const page=await context.newPage();
const errors=[];
const expectedNegativeErrors=[];
let checkingRevocation=false;
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error'){
 if(checkingRevocation&&m.text().includes('401 (Unauthorized)'))expectedNegativeErrors.push(m.text());
 else errors.push(m.text());
}});
const checks=[];
function check(name,ok){checks.push({name,pass:ok});if(!ok)throw new Error(name);}
try{
 await page.goto(base+'/s11.html');
 await page.getByRole('heading',{name:'Quello che hai provato.'}).waitFor();
 await page.getByRole('heading',{name:'poiseuille-v1'}).first().waitFor();
 check('page identity',(await page.title()).includes('Ardesia'));
 check('not blank and no overlay',(await page.locator('body').innerText()).includes('Le prove svolte')&&await page.locator('vite-error-overlay').count()===0);
 check('two canonical receipts',await page.locator('.insights-attempts > li').count()===2);
 await page.getByText('Mostra evidenza',{exact:true}).first().click();
 check('exact receipt/source evidence',await page.getByText('Ricevuta Core',{exact:true}).first().isVisible());
 await page.screenshot({path:path.join(output,'s11-desktop.png'),fullPage:true});
 const toggle=page.getByRole('checkbox');
 check('default optout',!(await toggle.isChecked()));
 await toggle.click();
 await page.getByRole('status').filter({hasText:'Analitica facoltativa attivata.'}).waitFor();
 await page.getByRole('button',{name:'Segnala difficoltà'}).first().click();
 await page.getByRole('status').filter({hasText:'Segnalazione registrata'}).waitFor();
 let report=await (await context.request.get(base+'/study/learning-insights/export?editionId='+access.editionId)).json();
 check('explicit difficulty persisted',report.optionalEvents.length===1&&report.optionalEvents[0].kind==='difficulty.reported');
 await page.reload();await page.getByRole('checkbox',{checked:true}).waitFor();
 check('cold page retains optional choice',await page.getByRole('checkbox').isChecked());
 await page.getByRole('checkbox').click();
 await page.getByRole('status').filter({hasText:'Analitica facoltativa disattivata'}).waitFor();
 report=await (await context.request.get(base+'/study/learning-insights/export?editionId='+access.editionId)).json();
 check('optout deletion while study preserved',report.optionalEvents.length===0&&report.attempts.length===2);
 await page.getByRole('button',{name:'Contesta questa indicazione'}).click();
 await page.getByLabel('Motivo della contestazione').fill('Prova sintetica: chiedo di rivedere il vincolo.');
 await page.getByRole('button',{name:'Invia contestazione'}).click();
 await page.getByRole('status').filter({hasText:'Contestazione inviata'}).waitFor();
 await page.getByRole('button',{name:'Contesta questa indicazione'}).waitFor({state:'detached'});
 check('contest updates canonical diary',await page.getByRole('button',{name:'Contesta questa indicazione'}).count()===0);
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Esporta i dati visibili'}).click();
 const download=await downloadPromise;
 await download.saveAs(path.join(output,'s11-export-synthetic.json'));
 check('export download',download.suggestedFilename()==='ardesia-learning-insights.json');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'s11-mobile.png'),fullPage:true});
 check('mobile has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('button',{name:'Aggiorna'}).focus();await page.keyboard.press('Tab');
 check('keyboard focus visible',await page.getByRole('button',{name:'Esporta i dati visibili'}).evaluate(e=>e===document.activeElement));
 check('reduced motion',await page.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches));
 check('console health before deliberate revocation',errors.length===0);
 await context.request.delete(base+'/study/session');
 checkingRevocation=true;
 const rejected=page.waitForResponse(r=>r.url().includes('/study/learning-insights?')&&r.status()===401);
 await page.getByRole('button',{name:'Aggiorna'}).click();await rejected;
 await page.getByRole('alert').waitFor();
 check('revocation removes private evidence',await page.locator('.insights-attempts > li').count()===0);
 check('console health',errors.length===0);
}finally{
 await writeFile(path.join(output,'s11-browser-checks.json'),JSON.stringify({environment:'local synthetic Core composition; shared mount pending',checks,errors,expectedNegativeErrors},null,2));
 await browser.close();
}
console.log(JSON.stringify({pass:checks.length,checks,errors}));
