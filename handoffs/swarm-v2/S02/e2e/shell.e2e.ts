import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
const accessPath = process.env.ARDESIA_DEMO_ACCESS;
test.beforeEach(async ({ context }) => {
  if (!accessPath) throw new Error("ARDESIA_DEMO_ACCESS must reference a fresh private synthetic seed");
  const access = JSON.parse(await readFile(accessPath, "utf8"));
  expect(access.synthetic).toBe(true);
  const response = await context.request.post("/study/session", {data:{token:access.tokens["student-01"]}});
  expect(response.ok()).toBe(true);
});
for (const width of [390, 820, 1440]) {
  test(`Oggi → ricerca → lezione → quaderno, reload and source persistence at ${width}px`, async ({ page, context }, info) => {
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.setViewportSize({width,height:1000});
    await page.emulateMedia({reducedMotion:"reduce"});
    await page.goto("/?view=today&edition=fluidi");
    await expect(page.getByRole("heading", {name:"Riprendiamo il filo."})).toBeVisible();
    expect(await page.title()).toContain("Ardesia");
    expect(await page.locator("vite-error-overlay").count()).toBe(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({path:info.outputPath(`today-${width}.png`),fullPage:true});
    const trigger = page.getByRole("button", {name:/Cerca nello spazio/});
    await trigger.click();
    const search = page.getByRole("searchbox", {name:"Cerca una destinazione"});
    await expect(search).toBeFocused();
    await search.fill("nessun-risultato");
    await expect(page.getByRole("status")).toContainText("Nessuna destinazione");
    await page.keyboard.press("Escape");
    await expect(trigger).toBeFocused();
    await page.keyboard.press("ControlOrMeta+k");
    await search.fill("esperimento");
    await page.screenshot({path:info.outputPath(`search-${width}.png`)});
    await search.press("ArrowDown");
    await expect(page.getByRole("dialog").getByRole("button", {name:/Lezione/})).toBeFocused();
    await page.keyboard.press("Enter");
    await expect(page).toHaveURL(/view=classroom/);
    await expect(page.getByRole("main")).toBeFocused();
    await expect(page.getByRole("navigation", {name:"Navigazione principale"}).getByRole("button", {name:"Lezione"})).toHaveAttribute("aria-current","page");
    await expect(page.getByRole("heading", {name:"Metti un’idea alla prova."})).toBeVisible();
    const note = `S02 synthetic note at ${width}px: confronto le unità.`;
    await page.getByLabel("Una nota, una domanda, un procedimento").fill(note);
    await page.getByRole("button", {name:"Salva nota privata",exact:true}).click();
    await expect(page.getByRole("status").filter({hasText:"Nota salvata nel tuo spazio privato."})).toBeVisible();
    await page.reload();
    await expect(page.getByRole("heading", {name:"Metti un’idea alla prova."})).toBeVisible();
    const workspace = await (await context.request.get("/study/workspace?editionId=fluidi")).json();
    expect(workspace.resources.some((resource: {text:string}) => resource.text === note)).toBe(true);
    await page.screenshot({path:info.outputPath(`lesson-${width}.png`),fullPage:true});
    await page.getByRole("button", {name:"Il mio lavoro",exact:true}).click();
    await page.getByRole("button", {name:"Quaderno",exact:true}).click();
    await expect(page.getByRole("heading", {name:"Il quaderno, con te."})).toBeVisible();
    await page.screenshot({path:info.outputPath(`notebook-${width}.png`),fullPage:true});
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await context.setOffline(true);
    await expect(page.getByRole("status").filter({hasText:"Il dispositivo segnala assenza di rete."})).toBeVisible();
    await context.setOffline(false);
    await expect(page.getByText(/Il dispositivo segnala assenza di rete/)).toHaveCount(0);
    await page.goto("/?view=classroom&edition=analisi");
    await expect(page.getByLabel("Edizione corrente")).toHaveValue("analisi");
    await page.reload();
    await expect(page.getByLabel("Edizione corrente")).toHaveValue("analisi");
    expect(errors).toEqual([]);
  });
}
test("teacher command destinations remain distinct from student and logout removes search", async ({page,context}) => {
  const access = JSON.parse(await readFile(accessPath!, "utf8"));
  expect((await context.request.post("/study/session",{data:{token:access.tokens["tutor-synthetic"]}})).ok()).toBe(true);
  await page.goto("/?view=today&edition=fluidi");
  await page.getByRole("button",{name:/Cerca nello spazio/}).click();
  const dialog=page.getByRole("dialog");
  await expect(dialog.getByRole("button",{name:/Da correggere/})).toBeVisible();
  await expect(dialog.getByRole("button",{name:/Prova di fisica/})).toHaveCount(0);
  await page.keyboard.press("Escape");
  await page.getByRole("button",{name:/Esci dall’account/}).click();
  await expect(page.getByRole("heading",{name:"La fisica. Un’idea alla volta."})).toBeVisible();
  await page.keyboard.press("ControlOrMeta+k");
  await expect(page.getByRole("dialog")).toHaveCount(0);
});

test("command results remain reachable in a short viewport with large text", async ({page}) => {
  await page.setViewportSize({width:390,height:320});
  await page.goto("/?view=today&edition=fluidi");
  await page.getByRole("button",{name:/Cerca nello spazio/}).click();
  await page.addStyleTag({content:'.ps-command {font-size:20px} .ps-command > p {font-size:18px}'});
  const results=page.locator('.ps-command-results');
  expect((await results.boundingBox())!.height).toBeGreaterThan(48);
  await page.getByRole('searchbox').press('ArrowDown');
  await page.keyboard.press('End');
  await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog')).toHaveCount(0);
});
