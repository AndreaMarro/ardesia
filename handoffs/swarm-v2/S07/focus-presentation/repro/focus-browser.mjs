import {createRequire} from 'node:module'
import {resolve} from 'node:path'
import {mkdir,writeFile} from 'node:fs/promises'
const root=resolve(process.env.ARDESIA_S07_ROOT??process.cwd())
const output=resolve(process.env.ARDESIA_S07_OUTPUT??'work/s07-focus-browser')
await mkdir(output,{recursive:true})
const require=createRequire(resolve(root,'apps/studio/package.json'))
const {chromium}=require('@playwright/test')
const started=performance.now(), errors=[],results=[],pages=[]
const browser=await chromium.launch({headless:true,args:['--remote-debugging-port=5477','--remote-debugging-address=127.0.0.1']})
const check=(value,label)=>{if(!value)throw Error(label);results.push({case:label,pass:true})}
const frame=page=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
const camera=page=>page.evaluate(()=>{const state=window.__MAESTRO_TEST__.apiRef.current.getAppState();return {x:state.scrollX,y:state.scrollY,zoom:state.zoom.value}})
const sameCamera=(a,b)=>Math.abs(a.x-b.x)<.01&&Math.abs(a.y-b.y)<.01&&a.zoom===b.zoom
try {
 for(const actor of ['alice','bob','carol']){
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce',hasTouch:true})
  const page=await context.newPage();pages.push(page)
  page.on('pageerror',e=>errors.push({actor,type:'pageerror',message:e.message}))
  page.on('console',m=>{if(['error','warning'].includes(m.type()))errors.push({actor,type:m.type(),message:m.text()})})
  page.on('response',r=>{if(r.status()>=400)errors.push({actor,type:'http',url:r.url(),status:r.status()})})
  await page.goto('http://127.0.0.1:5470/s07-proof.html?actor='+actor,{waitUntil:'domcontentloaded',timeout:60000})
  await page.waitForFunction(()=>window.s07?.source.pageCount===2&&window.__MAESTRO_TEST__?.apiRef.current,null,{timeout:60000})
  await page.getByRole('checkbox',{name:'Segui presentazione docente'}).waitFor()
 }
 const [teacher,student,independent]=pages
 const source=await teacher.evaluate(()=>window.s07.source)
 check((await Promise.all(pages.map(p=>p.evaluate(()=>window.s07.source.sha256)))).every(sha=>sha===source.sha256),'three contexts exact PDF source')
 check(await student.getByRole('button',{name:'Indica questo punto',exact:true}).count()===0,'viewer has no publishing command')
 await teacher.bringToFront()
 await teacher.getByLabel('Il tuo zoom',{exact:true}).selectOption('1.5')
 await teacher.getByLabel('Pagina del documento').selectOption('2')
 await teacher.getByRole('button',{name:'Indica questo punto',exact:true}).click()
 await teacher.getByRole('status').filter({hasText:'Punto della presentazione inviato'}).waitFor()
 const first=await teacher.evaluate(()=>window.s07.sentFocus().at(-1))
 check(first.target.page===2,'native viewport publisher resolves page two')
 const independentBefore=await camera(independent),studentBefore=await camera(student)
 await student.evaluate(value=>window.s07.receiveFocus(value),first)
 await independent.evaluate(value=>window.s07.receiveFocus(value),first)
 await frame(student)
 check(sameCamera(studentBefore,await camera(student))&&sameCamera(independentBefore,await camera(independent)),'no movement before participant consent')
 await student.bringToFront()
 await student.getByRole('checkbox',{name:'Segui presentazione docente'}).check()
 await student.waitForFunction(()=>document.querySelector('select[aria-label="Pagina del documento"]').value==='2')
 check((await camera(student)).zoom===studentBefore.zoom,'following keeps personal zoom')
 // Prepare the next real publisher packet before the viewer starts its gesture.
 await teacher.bringToFront();await teacher.getByLabel('Pagina del documento').selectOption('1')
 await teacher.getByRole('button',{name:'Indica questo punto',exact:true}).click()
 await teacher.waitForFunction(()=>window.s07.sentFocus().length===2)
 const second=await teacher.evaluate(()=>window.s07.sentFocus().at(-1))
 await student.bringToFront()
 const canvas=student.locator('canvas.interactive'),box=await canvas.boundingBox(),point={x:box.x+box.width/2,y:box.y+box.height/2}
 await student.keyboard.down('Space');await student.mouse.move(point.x,point.y);await student.mouse.down()
 await student.mouse.move(point.x+25,point.y+20,{steps:5})
 const panning=await camera(student)
 await student.evaluate(value=>window.s07.receiveFocus(value),second);await frame(student)
 check(await student.getByLabel('Pagina del documento').inputValue()==='2'&&sameCamera(panning,await camera(student)),'native Space pan holds camera while pointer stays down')
 await student.mouse.up();await student.keyboard.up('Space')
 await student.waitForFunction(()=>document.querySelector('select[aria-label="Pagina del documento"]').value==='1')
 check((await camera(student)).zoom===studentBefore.zoom,'queued pan focus applied after release with own zoom')
 const afterPan=await camera(student)
 await student.evaluate(value=>window.s07.receiveFocus(value),first);await student.evaluate(value=>window.s07.receiveFocus(value),second);await frame(student)
 check(sameCamera(afterPan,await camera(student)),'duplicate and reordered focus do not pull camera back')
 // A native pen gesture must commit its stroke before focus changes the selected page.
 await teacher.bringToFront();await teacher.getByLabel('Pagina del documento').selectOption('2')
 await teacher.getByRole('button',{name:'Indica questo punto',exact:true}).click()
 await teacher.waitForFunction(()=>window.s07.sentFocus().length===3)
 const third=await teacher.evaluate(()=>window.s07.sentFocus().at(-1))
 await student.bringToFront();await student.getByRole('button',{name:'Condiviso',exact:true}).click()
 await student.getByTestId('toolbar-freedraw').locator('..').click()
 await student.waitForFunction(()=>window.__MAESTRO_TEST__.apiRef.current.getAppState().activeTool.type==='freedraw')
 const pen=await student.evaluate(()=>window.s07.gesture())
 check((await student.evaluate(p=>document.elementFromPoint(p.x,p.y)?.className,pen)).includes('interactive'),'native pen starts on actual canvas')
 await student.mouse.move(pen.x,pen.y);await student.mouse.down();await student.mouse.move(pen.x+25,pen.y+20,{steps:5})
 await student.evaluate(value=>window.s07.receiveFocus(value),third);await frame(student)
 check(await student.getByLabel('Pagina del documento').inputValue()==='1','focus waits while native pen is still down')
 await student.mouse.up()
 await student.waitForFunction(()=>window.s07.dump().count===1&&document.querySelector('select[aria-label="Pagina del documento"]').value==='2')
 const captured=await student.evaluate(()=>window.s07.dump().objects[0])
 check(captured.source.page===1&&captured.authorId==='bob','native pointer-up captures stroke on original page before focus')
 check(sameCamera(independentBefore,await camera(independent)),'independent peer still controls its own view')
 await teacher.bringToFront();await teacher.evaluate(()=>window.s07.presentationMode('offline'))
 await teacher.getByRole('button',{name:'Indica questo punto',exact:true}).click()
 await teacher.getByRole('alert').filter({hasText:'Punto non inviato'}).waitFor()
 await teacher.evaluate(value=>window.s07.receiveFocus(value),third);await frame(teacher)
 check(await teacher.getByRole('alert').filter({hasText:'Punto non inviato'}).isVisible(),'incoming focus does not erase a publication failure')
 await teacher.evaluate(()=>window.s07.presentationMode('ok'))
 await teacher.getByRole('button',{name:'Indica questo punto',exact:true}).click()
 await teacher.waitForFunction(()=>window.s07.sentFocus().length===4)
 check(await teacher.getByRole('status').filter({hasText:'Punto della presentazione inviato'}).isVisible(),'explicit retry confirms the publication')
 await student.screenshot({path:resolve(output,'focus-desktop.png')})
 await student.setViewportSize({width:390,height:844})
 await student.getByRole('checkbox',{name:'Segui presentazione docente'}).uncheck()
 await student.getByRole('checkbox',{name:'Segui presentazione docente'}).check()
 check(!await student.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'mobile follow controls do not overflow')
 await student.screenshot({path:resolve(output,'focus-mobile.png')})
 await student.evaluate(()=>window.s07.revokeInk())
 await student.getByRole('status').filter({hasText:'Accesso revocato'}).waitFor()
 const revokedView=await camera(student)
 await student.evaluate(value=>window.s07.receiveFocus({...value,sequence:50,target:{...value.target,page:1}}),third);await frame(student)
 check(await student.getByRole('checkbox',{name:'Segui presentazione docente'}).count()===0&&sameCamera(revokedView,await camera(student)),'InkSession revocation removes follow and rejects later camera movement')
 await teacher.bringToFront();await teacher.evaluate(()=>window.s07.presentationMode('pending'))
 await teacher.getByRole('button',{name:'Indica questo punto',exact:true}).click()
 await teacher.getByRole('button',{name:'Invio punto…',exact:true}).waitFor()
 await teacher.evaluate(()=>window.s07.revoke())
 await teacher.getByRole('status').filter({hasText:'Accesso revocato'}).waitFor()
 check(await teacher.evaluate(()=>window.s07.sentFocus().length)===4&&await teacher.getByRole('status').filter({hasText:'Punto della presentazione inviato'}).count()===0,'host revocation aborts pending publication without false success')
 if(errors.length)throw Error('unexpected browser errors: '+JSON.stringify(errors))
 const report={source,browser:browser.version(),node:process.version,sourceCommit:process.env.ARDESIA_S07_SHA??null,results,errors,durationMs:Math.round(performance.now()-started),transport:'synthetic host port and explicit packet transfer, no Core auth/server/websocket',mobile:'Chromium emulation; no physical device'}
 await writeFile(resolve(output,'focus-browser.json'),JSON.stringify(report,null,2))
 console.log(JSON.stringify(report))
 if(process.env.ARDESIA_S07_REA_HOLD==='1'){
  await writeFile(resolve(output,'rea-ready.json'),JSON.stringify({cdpEndpoint:'http://127.0.0.1:5477',url:'http://127.0.0.1:5470/s07-proof.html?actor=carol'}))
  console.log('REA snapshot ready; browser retained for up to 45 seconds')
  await new Promise(resolve=>setTimeout(resolve,45000))
 }
}catch(error){
 console.error(JSON.stringify({error:String(error),errors,body:await pages[1]?.locator('body').innerText().catch(()=>null)}))
 await pages[1]?.screenshot({path:resolve(output,'focus-failure.png')}).catch(()=>{})
 throw error
}finally{await browser.close()}
