 for(const note of existing.filter(n=>!keep.has(n.id)))await context.request.post(origin+'/study/memory/notes/'+note.id+'/delete',{
   data:{expectedVersion:note.version},headers:{'Idempotency-Key':crypto.randomUUID()}});
