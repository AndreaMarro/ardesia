 await page.getByLabel('La tua nota',{exact:true}).fill('Ritrovo il vincolo anche dopo una nuova sessione.');
 await page.getByLabel('Come descrivi questo passaggio?').selectOption('not_understood');
 await page.getByRole('button',{name:'Salva nel quaderno',exact:true}).click();
