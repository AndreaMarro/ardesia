import {chromium,expect as baseExpect} from '../../../node_modules/@playwright/test/index.mjs';
import fs from 'node:fs/promises';
const root=process.env.ARDESIA_S05_DEMO_DIR+'/';
const fixture=JSON.parse(await fs.readFile(root+'s05-demo-fixture.json','utf8'));
const origin='http://127.0.0.1:5425';
