from collections.abc import Iterable, Mapping
from typing import Protocol


class StudyRepository(Protocol):
    def now(self) -> int: ...
    def entitled(self, user: Mapping, rows: list, course: str) -> bool: ...
    def published(self) -> list: ...
    def record(self, key: str, version: int) -> dict: ...
    def attempts(self, uid: str) -> Iterable[Mapping]: ...
    def seen(self, uid: str) -> set[str]: ...
    def previous_run(self, uid: str, signature: str) -> str | None: ...
    def exam_policy(self, rows: list, course: str) -> dict | None: ...
    def run_policy(self, rid: str, course: str) -> dict | None: ...
    def create_run(self, rid: str, uid: str, course: str, mode: str, stamp: int,
                   deadline: int | None, items: list, signature: str, policy: dict | None) -> None: ...
    def expose(self, uid: str, key: str, version: int) -> bool: ...
    def add_attempt(self, rid: str, index: int, uid: str, question: dict, correct: bool, aided: bool, stamp: int) -> None: ...
    def run(self, rid: str, uid: str) -> Mapping | None: ...
    def save_run(self, rid: str, items: list, finished: int | None) -> None: ...
    def recovery_attempt(self, uid: str, skill: str) -> Mapping | None: ...
    def observations(self, uid: str) -> list: ...
    def reads(self, uid: str) -> list: ...
    def recent_runs(self, uid: str) -> list: ...
    def observation_count(self, uid: str) -> int: ...
    def historical_runs(self, uid: str) -> Iterable[Mapping]: ...
