#!/usr/bin/env python3
"""Materialize every selectable public lab state using the canonical Core.

No formula is implemented in the browser. --check fails on stale generated data.
This requires only Python's standard library, not a database or the HTTP server.
"""
import argparse
from decimal import Decimal
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'packages/engine'))

from lessonos.study.activities import evaluate_activity  # noqa: E402
from lessonos.study.public_preview import (  # noqa: E402
    RADIUS_MAX, RADIUS_MIN, RADIUS_STEP, public_course,
)

OUTPUT = ROOT / 'apps/web/src/generated/publicPreviewData.ts'
SOURCES = (
    'packages/engine/lessonos/study/activities.py',
    'packages/engine/lessonos/study/public_preview.py',
)


def build_projection():
    cases = []
    radius = Decimal(str(RADIUS_MIN))
    while radius <= Decimal(str(RADIUS_MAX)):
        for boundary in ('pressure', 'flow'):
            parameters = {'radiusRatio': float(radius), 'boundary': boundary}
            cases.append({
                'parameters': parameters,
                'result': evaluate_activity('poiseuille-v1', parameters),
            })
        radius += Decimal(str(RADIUS_STEP))
    return {
        'schemaVersion': 1,
        'sources': {path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest()
                    for path in SOURCES},
        'course': public_course(),
        'radius': {'min': RADIUS_MIN, 'max': RADIUS_MAX, 'step': RADIUS_STEP},
        'cases': cases,
    }


def render_projection():
    projection = build_projection()
    cases = projection.pop('cases')
    header = json.dumps(projection, ensure_ascii=False, indent=2)[:-2]
    rows = ',\n'.join('    ' + json.dumps(case, ensure_ascii=False) for case in cases)
    return (
        '// Generated by bin/web/export_public_preview.py; do not edit by hand.\n'
        '// These are Core results for every allowed slider state, not exam questions.\n'
        f'export const publicPreviewData = {header},\n  "cases": [\n{rows}\n  ]\n}} as const;\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render_projection()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print('STALE public preview: run python3 bin/web/export_public_preview.py', file=sys.stderr)
            return 1
        print('PASS: public course and all 62 lab states match the current Core')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
