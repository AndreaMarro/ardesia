#!/usr/bin/env python3
"""Materialize every selectable public lab state using the canonical Core.

No formula is implemented in the browser. --check fails on stale generated data.
This requires only Python's standard library, not a database or the HTTP server.
"""
import argparse
from decimal import Decimal
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'packages/engine'))

from lessonos.study.activities import evaluate_activity  # noqa: E402
from lessonos.study.public_preview import (  # noqa: E402
    RADIUS_MAX, RADIUS_MIN, RADIUS_STEP, public_course,
)

OUTPUT = ROOT / 'apps/web/src/generated/publicPreviewData.ts'
SOURCES = (
    'packages/engine/lessonos/study/activities.py',
    'packages/engine/lessonos/study/spring.py',
    'packages/engine/lessonos/study/public_preview.py',
    'bin/web/poiseuille-demo.json',
    'bin/web/export_public_preview.py',
)


def project_case(parameters):
    result = evaluate_activity('poiseuille-v1', parameters)
    return {'parameters': parameters, 'visual': result.pop('visual'), 'result': result}


def build_projection():
    demo = json.loads((ROOT / 'bin/web/poiseuille-demo.json').read_text())
    if (demo.get('schemaVersion') != 1 or demo.get('objectId') != 'poiseuille-formula'
            or demo.get('audioPath') != 'lesson-demo/poiseuille.wav'
            or demo.get('syntheticVoice') is not True
            or not isinstance(demo.get('transcript'), str) or not demo['transcript'].strip()
            or not isinstance(demo.get('authorship'), str) or not demo['authorship'].strip()):
        raise ValueError('Invalid authored public demonstration passage')
    audio = ROOT / 'apps/web/public' / demo['audioPath']
    demo['audioSha256'] = hashlib.sha256(audio.read_bytes()).hexdigest()
    cases = []
    radius = Decimal(str(RADIUS_MIN))
    while radius <= Decimal(str(RADIUS_MAX)):
        for boundary in ('pressure', 'flow'):
            parameters = {'radiusRatio': float(radius), 'boundary': boundary}
            cases.append(project_case(parameters))
        radius += Decimal(str(RADIUS_STEP))
    return {
        'schemaVersion': 1,
        'transferCase': {'id': 'viscosity-length-fixed-flow-v1', **project_case({
            'radiusRatio': 1, 'boundary': 'flow', 'viscosity': 2, 'length': 2,
        })},
        'lessonDemo': demo,
        'visualModel': {'representation': 'Schematic mean transport speed, not a local velocity profile.',
                        'derivation': 'Mean speed ratio = Core flow ratio / radius ratio squared; Q = v_mean A.'},
        'sources': {path: hashlib.sha256((ROOT / path).read_bytes()).hexdigest()
                    for path in SOURCES},
        'course': public_course(),
        'radius': {'min': RADIUS_MIN, 'max': RADIUS_MAX, 'step': RADIUS_STEP},
        'cases': cases,
        'hydrostatic': {
            'depth': {'min': 0, 'max': 4, 'step': .5},
            'densities': [1000, 800],
            'surfacePressure': 101325,
            'cases': [
                {'parameters': parameters,
                 'result': evaluate_activity('hydrostatic-v1', parameters)}
                for depth in range(9)
                for density in (1000, 800)
                for reference in ('gauge', 'absolute')
                for parameters in [{'depth': depth / 2, 'density': density,
                                    'g': 9.81, 'surfacePressure': 101325,
                                    'reference': reference}]
            ],
        },
        'spring': {
            'force': {'min': 0, 'max': 10, 'step': .5},
            'stiffnesses': [20, 40, 80],
            'maxExtension': .5,
            'cases': [
                {'parameters': parameters,
                 'result': evaluate_activity('hooke-v1', parameters)}
                for force in range(21)
                for stiffness in (20, 40, 80)
                for parameters in [{'force': force / 2, 'stiffness': stiffness}]
            ],
        },
        'demonstration': {
            'provenance': 'DEMO',
            'authorship': 'Original Ardesia educational scenarios, independent of the question bank.',
            'numericalVerification': 'Deterministic canonical Core; independent SI oracle tests.',
            'humanEditorialApproval': False,
            'meaning': 'Numerical verification is separate from human scientific/editorial approval.',
        },
    }


def render_projection():
    projection = build_projection()
    cases = projection.pop('cases')
    header = json.dumps(projection, ensure_ascii=False, indent=2)[:-2]
    rows = ',\n'.join('    ' + json.dumps(case, ensure_ascii=False) for case in cases)
    return (
        '// Generated by bin/web/export_public_preview.py; do not edit by hand.\n'
        '// Core results: every allowed slider state and one distinct authored transfer.\n'
        f'export const publicPreviewData = {header},\n  "cases": [\n{rows}\n  ]\n}} as const;\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render_projection()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print('STALE public preview: run python3 bin/web/export_public_preview.py', file=sys.stderr)
            return 1
        print('PASS: public course, 62 Poiseuille + 36 hydrostatic + 63 spring states and the distinct transfer match the current Core')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print(f'Wrote {OUTPUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
