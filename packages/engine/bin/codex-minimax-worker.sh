#!/usr/bin/env bash
# ARDESIA — Codex worker backed by MiniMax-M3.
# Conservative lane: Hermes remains blind; this worker uses its own CODEX_HOME,
# a Codex custom provider, a Keychain-backed token helper, JSONL logs, and an
# explicit sandbox per run.
set -euo pipefail

MODE="${1:-review}"
if [ "$#" -gt 0 ]; then shift || true; fi

REPO="${ARDESIA_CODEX_REPO:-${PWD}}"
CODEX_HOME_DIR="${ARDESIA_CODEX_HOME:-$HOME/.codex-minimax-m3}"
LOG_DIR="${ARDESIA_CODEX_LOG_DIR:-$HOME/maestro-logs/codex-minimax}"
MODEL="${MINIMAX_CODEX_MODEL:-MiniMax-M3}"
BASE_URL="${MINIMAX_CODEX_BASE_URL:-https://api.minimax.io/v1}"
SERVICE_NAME="${MINIMAX_KEYCHAIN_SERVICE:-ardesia-minimax-api-key}"
ACCOUNT_NAME="${MINIMAX_KEYCHAIN_ACCOUNT:-$USER}"

usage() {
  cat <<'USAGE'
Usage:
  bash packages/engine/bin/codex-minimax-worker.sh setup-key
  bash packages/engine/bin/codex-minimax-worker.sh review [repo-path]
  bash packages/engine/bin/codex-minimax-worker.sh plan [repo-path]
  bash packages/engine/bin/codex-minimax-worker.sh repair "task..." [repo-path]
  bash packages/engine/bin/codex-minimax-worker.sh custom "task..." [repo-path]

Modes:
  setup-key  Store $MINIMAX_API_KEY in macOS Keychain as ardesia-minimax-api-key.
  review     Read-only adversarial review of current repo/diff.
  plan       Read-only implementation plan for the next safe task.
  repair     Workspace-write minimal patch for the provided task.
  custom     Workspace-write custom Codex task.

Environment:
  MINIMAX_API_KEY             only needed by setup-key; not passed to Codex runs.
  MINIMAX_CODEX_MODEL         default: MiniMax-M3.
  MINIMAX_CODEX_BASE_URL      default: https://api.minimax.io/v1.
  ARDESIA_CODEX_HOME          default: ~/.codex-minimax-m3.
  ARDESIA_CODEX_REPO          default: current directory.
  ARDESIA_CODEX_LOG_DIR       default: ~/maestro-logs/codex-minimax.
USAGE
}

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || { echo "missing command: $1" >&2; exit 127; }
}

setup_key() {
  need_cmd security
  if [ -z "${MINIMAX_API_KEY:-}" ]; then
    echo "MINIMAX_API_KEY is empty. Set it only for this setup step, then unset it." >&2
    echo "Example: read -rsp 'MiniMax key: ' MINIMAX_API_KEY; export MINIMAX_API_KEY; bash $0 setup-key; unset MINIMAX_API_KEY" >&2
    exit 2
  fi
  security add-generic-password -U -a "$ACCOUNT_NAME" -s "$SERVICE_NAME" -w "$MINIMAX_API_KEY" >/dev/null
  echo "stored MiniMax key in macOS Keychain service=$SERVICE_NAME account=$ACCOUNT_NAME"
}

write_token_helper() {
  mkdir -p "$CODEX_HOME_DIR/bin"
  local helper="$CODEX_HOME_DIR/bin/minimax-token"
  cat > "$helper" <<'HELPER'
#!/usr/bin/env bash
set -euo pipefail
service="${MINIMAX_KEYCHAIN_SERVICE:-ardesia-minimax-api-key}"
account="${MINIMAX_KEYCHAIN_ACCOUNT:-$USER}"
if ! command -v security >/dev/null 2>&1; then
  echo "macOS security command not found; store the MiniMax key in Keychain or adapt the token helper" >&2
  exit 127
fi
security find-generic-password -a "$account" -s "$service" -w
HELPER
  chmod 700 "$helper"
  printf '%s' "$helper"
}

write_codex_config() {
  mkdir -p "$CODEX_HOME_DIR" "$LOG_DIR"
  local helper
  helper="$(write_token_helper)"
  cat > "$CODEX_HOME_DIR/config.toml" <<EOF
# Generated by ARDESIA codex-minimax-worker.sh.
# User-level Codex config: provider/model config belongs under CODEX_HOME, not
# project-local .codex/config.toml.
model = "$MODEL"
model_provider = "minimax"
model_reasoning_effort = "medium"
model_reasoning_summary = "concise"

[model_providers.minimax]
name = "MiniMax"
base_url = "$BASE_URL"
wire_api = "responses"
request_max_retries = 2
stream_max_retries = 2
stream_idle_timeout_ms = 600000

[model_providers.minimax.auth]
command = "$helper"
timeout_ms = 5000
refresh_interval_ms = 0
EOF
}

build_prompt() {
  local task="${1:-}"
  case "$MODE" in
    review)
      cat <<'PROMPT'
You are the ARDESIA Codex worker running MiniMax-M3. Act as a balanced adversarial reviewer, not the main builder.

Rules:
- Do not edit files.
- Do not read, print, infer, or request secrets.
- Inspect repository structure, git status/diff, and relevant tests only.
- Focus on concrete product/factory risks: regressions, overclaims, missing gates, fragile scripts, unsafe secret flow, and test tautologies.
- Output: findings ranked P0/P1/P2, each with evidence and the smallest safe next action.
PROMPT
      ;;
    plan)
      cat <<'PROMPT'
You are the ARDESIA Codex worker running MiniMax-M3. Produce a small, executable plan for one safe next task.

Rules:
- Do not edit files.
- Do not read, print, infer, or request secrets.
- Prefer high-leverage, low-risk work that improves the product or factory measurably.
- Output: one recommended task, files likely touched, acceptance criteria, tests/gates, and rollback.
PROMPT
      ;;
    repair)
      if [ -z "$task" ]; then echo "repair requires a task string" >&2; exit 2; fi
      cat <<PROMPT
You are the ARDESIA Codex worker running MiniMax-M3. Make the smallest safe patch for this task:

$task

Rules:
- Stay strictly in scope.
- Do not touch eval/gate.sh or weaken tests.
- Do not read, print, infer, or request secrets.
- Prefer minimal diffs and explicit validation.
- After editing, run only relevant cheap checks when available and summarize what changed.
PROMPT
      ;;
    custom)
      if [ -z "$task" ]; then echo "custom requires a task string" >&2; exit 2; fi
      printf '%s\n' "$task"
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
}

run_codex() {
  need_cmd codex
  write_codex_config

  local prompt sandbox run_id out last repo_arg
  repo_arg="${2:-}"
  [ -n "$repo_arg" ] && REPO="$repo_arg"
  cd "$REPO"

  case "$MODE" in
    review|plan) sandbox="read-only" ;;
    repair|custom) sandbox="workspace-write" ;;
    *) usage >&2; exit 2 ;;
  esac

  prompt="$(build_prompt "${1:-}")"
  run_id="$(date -u +%Y%m%dT%H%M%SZ)-$MODE"
  out="$LOG_DIR/codex-minimax-$run_id.jsonl"
  last="$LOG_DIR/codex-minimax-$run_id.md"

  # Keep provider secret out of the environment inherited by Codex/tool commands.
  # Codex obtains the MiniMax bearer token through CODEX_HOME/bin/minimax-token.
  env -u OPENAI_API_KEY -u OPENROUTER_API_KEY -u MINIMAX_API_KEY \
    CODEX_HOME="$CODEX_HOME_DIR" \
    codex exec --ephemeral --json --sandbox "$sandbox" -o "$last" "$prompt" > "$out"

  echo "codex-minimax mode=$MODE sandbox=$sandbox repo=$REPO"
  echo "jsonl=$out"
  echo "last_message=$last"
}

case "$MODE" in
  setup-key)
    setup_key
    ;;
  -h|--help|help)
    usage
    ;;
  repair|custom)
    run_codex "${1:-}" "${2:-}"
    ;;
  review|plan)
    run_codex "" "${1:-}"
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac
