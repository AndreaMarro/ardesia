#!/usr/bin/env bash
# ARDESIA — OpenAI Codex worker lane.
# Uses Codex with GPT-5.5 and medium reasoning. Intended to be invoked by
# Hermes-Codex or by the dual orchestrator, not as a default autonomous builder.
set -euo pipefail

MODE="${1:-review}"
if [ "$#" -gt 0 ]; then shift || true; fi

REPO="${ARDESIA_CODEX_REPO:-${PWD}}"
CODEX_HOME_DIR="${ARDESIA_CODEX_OPENAI_HOME:-$HOME/.codex-openai-gpt55-medium}"
LOG_DIR="${ARDESIA_CODEX_LOG_DIR:-$HOME/maestro-logs/codex-openai}"
MODEL="${ARDESIA_CODEX_MODEL:-gpt-5.5}"
REASONING="${ARDESIA_CODEX_REASONING:-medium}"
SANDBOX_READ="read-only"
SANDBOX_WRITE="workspace-write"

usage() {
  cat <<'USAGE'
Usage:
  bash packages/engine/bin/codex-openai-worker.sh review [repo-path]
  bash packages/engine/bin/codex-openai-worker.sh plan [repo-path]
  bash packages/engine/bin/codex-openai-worker.sh repair "task..." [repo-path]
  bash packages/engine/bin/codex-openai-worker.sh custom "task..." [repo-path]

Defaults:
  model: gpt-5.5
  reasoning effort: medium
  CODEX_HOME: ~/.codex-openai-gpt55-medium

Auth:
  Use Codex saved auth or pass CODEX_API_KEY only inline for a single invocation.
  Do not export OPENAI_API_KEY/CODEX_API_KEY globally in the factory job.
USAGE
}

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || { echo "missing command: $1" >&2; exit 127; }
}

write_codex_config() {
  mkdir -p "$CODEX_HOME_DIR" "$LOG_DIR"
  cat > "$CODEX_HOME_DIR/config.toml" <<EOF
# Generated by ARDESIA codex-openai-worker.sh.
# User-level Codex config. Do not place provider/auth config in project .codex.
model = "$MODEL"
model_provider = "openai"
model_reasoning_effort = "$REASONING"
model_reasoning_summary = "concise"
model_context_window = 1000000
EOF
}

build_prompt() {
  local task="${1:-}"
  case "$MODE" in
    review)
      cat <<'PROMPT'
You are the ARDESIA Hermes-Codex worker using Codex GPT-5.5 with medium reasoning.

Role:
- Be the high-precision reviewer/repair planner, not the always-on builder.
- Prefer correctness, product convergence, and falsifiable gates over activity.

Rules:
- Do not read, print, infer, or request secrets.
- Do not edit files in review mode.
- Inspect repository state, relevant docs, git status/diff, tests, and factory scripts.
- Flag overclaims, unsafe secret flow, weak tests, churn, missing product gates, and regressions.
- Output P0/P1/P2 findings with evidence and one smallest next action.
PROMPT
      ;;
    plan)
      cat <<'PROMPT'
You are the ARDESIA Hermes-Codex planner using Codex GPT-5.5 with medium reasoning.

Produce one bounded next task for the factory.
Rules:
- Do not edit files.
- Choose one task that measurably improves ARDESIA product or factory reliability.
- Avoid meta-work unless it unlocks product work.
- Output: task, why now, files likely touched, acceptance criteria, tests/gates, rollback.
PROMPT
      ;;
    repair)
      [ -n "$task" ] || { echo "repair requires a task string" >&2; exit 2; }
      cat <<PROMPT
You are the ARDESIA Hermes-Codex repair worker using Codex GPT-5.5 with medium reasoning.

Task:
$task

Rules:
- Make the smallest safe patch.
- Do not touch eval/gate.sh.
- Do not weaken or delete tests to pass gates.
- Do not read, print, infer, or request secrets.
- Run only relevant cheap checks when available; state exactly what passed or failed.
PROMPT
      ;;
    custom)
      [ -n "$task" ] || { echo "custom requires a task string" >&2; exit 2; }
      printf '%s\n' "$task"
      ;;
    *) usage >&2; exit 2 ;;
  esac
}

run_codex() {
  need_cmd codex
  write_codex_config

  local prompt sandbox run_id out last repo_arg
  repo_arg="${2:-}"
  [ -n "$repo_arg" ] && REPO="$repo_arg"
  cd "$REPO"

  case "$MODE" in
    review|plan) sandbox="$SANDBOX_READ" ;;
    repair|custom) sandbox="$SANDBOX_WRITE" ;;
    *) usage >&2; exit 2 ;;
  esac

  prompt="$(build_prompt "${1:-}")"
  run_id="$(date -u +%Y%m%dT%H%M%SZ)-$MODE"
  out="$LOG_DIR/codex-openai-$run_id.jsonl"
  last="$LOG_DIR/codex-openai-$run_id.md"

  env -u OPENAI_API_KEY -u OPENROUTER_API_KEY -u MINIMAX_API_KEY \
    CODEX_HOME="$CODEX_HOME_DIR" \
    codex exec \
      --ephemeral \
      --json \
      --model "$MODEL" \
      --config "model_reasoning_effort=$REASONING" \
      --sandbox "$sandbox" \
      --output-last-message "$last" \
      "$prompt" > "$out"

  printf 'codex-openai mode=%s model=%s reasoning=%s sandbox=%s repo=%s\n' "$MODE" "$MODEL" "$REASONING" "$sandbox" "$REPO"
  printf 'jsonl=%s\nlast_message=%s\n' "$out" "$last"
}

case "$MODE" in
  -h|--help|help) usage ;;
  repair|custom) run_codex "${1:-}" "${2:-}" ;;
  review|plan) run_codex "" "${1:-}" ;;
  *) usage >&2; exit 2 ;;
esac
