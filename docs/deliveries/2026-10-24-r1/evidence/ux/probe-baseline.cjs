const {chromium} = require('../../../work/ardesia/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
const output = __dirname;
let browser;
(async () => {
  browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto('http://127.0.0.1:5414/esperienza/?percorso=fluidi-termodinamica');
  await page.getByRole('heading',{name:'Che cosa tieni fisso?'}).waitFor();
  await page.getByLabel('Rapporto previsto',{exact:true}).fill('4');
  await page.getByRole('button',{name:'Metti alla prova',exact:true}).click();
  await page.getByTestId('physics-ratio').waitFor();
  const retry=page.getByRole('button',{name:'Prova di nuovo',exact:true});
  await retry.focus();
  await page.keyboard.press('Enter');
  const retryFocus=await page.evaluate(() => ({tag:document.activeElement.tagName,label:document.activeElement.getAttribute('aria-label')}));
  await page.screenshot({path:path.join(output,'baseline-retry-390.png'),fullPage:true});
  await page.getByLabel('Rapporto previsto',{exact:true}).fill('4');
  await page.getByRole('button',{name:'Metti alla prova',exact:true}).click();
  await page.getByRole('button',{name:'Un problema diverso',exact:true}).click();
  await page.getByRole('combobox',{name:/Grandezza fissata/}).selectOption('pressure');
  const mismatch={prompt:await page.locator('.transfer-prompt').innerText(),constraint:await page.getByRole('combobox',{name:/Grandezza fissata/}).inputValue(),model:await page.locator('.model-key').innerText()};
  await page.screenshot({path:path.join(output,'baseline-stale-task-390.png'),fullPage:true});
  fs.writeFileSync(path.join(output,'baseline-defects.json'),JSON.stringify({url:page.url(),browser:browser.version(),retryFocus,focusExpected:'Rapporto previsto',mismatch,errors},null,2));
  await browser.close();
})().catch(error => {console.error(error);process.exitCode=1;}).finally(() => browser?.close());
