_FIXTURE_PATH = (
    __import__("pathlib").Path(__file__).resolve().parents[1]
    / "fixtures"
    / "raw_transcript"
    / "lesson_derivatives.txt"
)


def _load_placeholder_text() -> str:
    """Load the PLACEHOLDER raw transcript fixture text."""
    return _FIXTURE_PATH.read_text()


def _build_mock_router_for_raw(
    raw_text: str,
    lesson_id: str = "raw_lesson",
    source_id: str = "raw_lesson",
) -> Router:
    """Build a mock router with payloads grounded on actual chunked seg_ids.

    First chunks the text, then builds mock payloads that reference the
    REAL seg_ids generated by the chunker.  This ensures no fabricated
    seg_ids in the mock — a groundedness-invariant test pattern.
    """
    chunk_result = chunk_raw_text(raw_text, source_id=source_id)
    assert len(chunk_result.items) > 0, "Chunker produced no items"

    store = SQLiteStore(":memory:")
    _ingest_chunk_result(store, lesson_id, chunk_result)
    segments = store.segments_for_lesson(lesson_id)
    assert len(segments) > 0, "No segments after ingest"

    real_seg_ids = [seg.seg_id for seg in segments]

    seg_prompt = build_segmentation_prompt(segments)
    ext_prompt = build_extraction_prompt(segments)

    # Build mock payloads using REAL seg_ids from chunker
    seg_payload: list[dict] = []
    # Group chunks into topics (e.g. first few seg_ids -> first topic)
    chunk_group_size = max(1, len(real_seg_ids) // 3)
    for i in range(0, len(real_seg_ids), chunk_group_size):
        group = real_seg_ids[i : i + chunk_group_size]
        seg_payload.append({"topic": f"Topic {i // chunk_group_size + 1}", "seg_ids": group})

    if not seg_payload:
        seg_payload = [{"topic": "Main topic", "seg_ids": list(real_seg_ids)}]

    first_seg = real_seg_ids[0] if real_seg_ids else "raw_lesson_s0"
    ext_payload = {
        "concepts": [
            {
                "name": "test concept",
                "status": "introduced",
                "citations": [{"seg_id": first_seg, "excerpt": segments[0].text[:50]}],
            },
        ],
        "exercises": [
            {
                "prompt": "Test exercise",
                "citations": [{"seg_id": first_seg, "excerpt": segments[0].text[:30]}],
            },
        ],
        "student_questions": [
            {
                "question": "What is the test?",
                "citations": [{"seg_id": first_seg, "excerpt": segments[0].text[:20]}],
            },
        ],
        "homework": [
            {
                "task": "Test homework",
                "citations": [{"seg_id": first_seg, "excerpt": segments[0].text[:15]}],
            },
        ],
    }

    router = Router()
    router.register(
        MockProvider(
            {
                seg_prompt: json.dumps(seg_payload),
                ext_prompt: json.dumps(ext_payload),
            }
        )
    )
    return router


