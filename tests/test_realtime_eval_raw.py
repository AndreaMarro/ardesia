class TestRawTranscriptEvalMockRoundtrip:
    """End-to-end run with mock LLM on the PLACEHOLDER fixture."""

    def test_placeholder_text_produces_report(self) -> None:
        """Running eval on the PLACEHOLDER fixture returns a valid report."""
        raw_text = _load_placeholder_text()
        router = _build_mock_router_for_raw(raw_text)
        report = run_raw_transcript_eval(
            raw_text,
            lesson_id="raw_placeholder",
            router=router,
        )
        assert report.error is None, f"Unexpected error: {report.error}"
        assert report.capsule is not None
        # Chunking should produce segments
        assert report.num_chunks >= 1
        # Mock LLM should produce at least 1 topic
        assert report.num_topics >= 1
        # Groundedness should be 1.0 (mock payloads use real seg_ids)
        assert report.groundedness_score == 1.0
        assert report.groundedness_passed is True
        # Excerpt accuracy should be 1.0 (excerpts are substrings of real segment text)
        assert report.excerpt_accuracy_score == 1.0
        assert report.excerpt_accuracy_passed is True
        # Total citations >= 1
        assert report.total_citations >= 1
        # Cost should be 0 (mock)
        assert report.total_cost_usd == 0.0
        # 2 calls: segmentation + extraction
        assert report.llm_calls == 2

    def test_empty_text_returns_error(self) -> None:
        """Empty text produces an error report."""
        report = run_raw_transcript_eval(
            "",
            lesson_id="empty_test",
            router=Router(),
        )
        assert report.error is not None
        assert "Empty" in report.error
        assert report.capsule is None

    def test_whitespace_only_returns_error(self) -> None:
        """Whitespace-only text produces an error report."""
        report = run_raw_transcript_eval(
            "   \n  \t  ",
            lesson_id="whitespace_test",
            router=Router(),
        )
        assert report.error is not None
        assert "Empty" in report.error

    def test_non_tautological_rejects_bad_seg_id(self) -> None:
        """Deliberately inject a citation with a non-existent seg_id.

        The extraction module validates seg_ids against persisted segments
        at construction time, so a fabricated seg_id raises ValueError.
        """
        raw_text = _load_placeholder_text()
        chunk_result = chunk_raw_text(raw_text)
        store = SQLiteStore(":memory:")
        _ingest_chunk_result(store, "bad_test", chunk_result)
        segments = store.segments_for_lesson("bad_test")
        assert len(segments) > 0

        seg_prompt = build_segmentation_prompt(segments)
        ext_prompt = build_extraction_prompt(segments)

        # Valid segmentation
        real_seg_ids = [s.seg_id for s in segments]
        seg_payload = [{"topic": "A", "seg_ids": list(real_seg_ids)}]

        # FABRICATED seg_id in extraction payload
        ext_payload = {
            "concepts": [
                {
                    "name": "fake",
                    "status": "introduced",
                    "citations": [{"seg_id": "fake_s99", "excerpt": "fake text"}],
                },
            ],
            "exercises": [],
            "student_questions": [],
            "homework": [],
        }

        router = Router()
        router.register(
            MockProvider(
                {
                    seg_prompt: json.dumps(seg_payload),
                    ext_prompt: json.dumps(ext_payload),
                }
            )
        )

        report = run_raw_transcript_eval(
            raw_text,
            lesson_id="bad_test",
            router=router,
        )
        assert report.error is not None
        assert "Assembly failed" in report.error

    def test_quality_metrics_populated(self) -> None:
        """Quality metrics (chunks, topics, concepts, ratio) are populated."""
        raw_text = _load_placeholder_text()
        router = _build_mock_router_for_raw(raw_text)
        report = run_raw_transcript_eval(
            raw_text,
            lesson_id="quality_test",
            router=router,
        )
        assert report.num_chunks > 0
        assert report.num_topics > 0
        assert report.num_concepts > 0
        # chunks_with_topics = chunks / topics (should be >= 1.0 since
        # each topic groups at least one chunk)
        assert report.chunks_with_topics >= 1.0
        assert report.source_type == "raw"
        # failure_modes is a tuple (may be empty or populated)
        assert isinstance(report.failure_modes, tuple)

    def test_failure_modes_one_topic_per_chunk(self) -> None:
        """If each chunk gets its own topic, a failure mode is reported."""
        raw_text = _load_placeholder_text()
        chunk_result = chunk_raw_text(raw_text)
        store = SQLiteStore(":memory:")
        _ingest_chunk_result(store, "failure_test", chunk_result)
        segments = store.segments_for_lesson("failure_test")

        seg_prompt = build_segmentation_prompt(segments)
        ext_prompt = build_extraction_prompt(segments)

        # Each chunk gets its OWN topic -> one-topic-per-chunk failure mode
        real_seg_ids = [s.seg_id for s in segments]
        seg_payload = [{"topic": f"Topic_{s}", "seg_ids": [s]} for s in real_seg_ids]

        ext_payload = {
            "concepts": [
                {
                    "name": "concept",
                    "status": "introduced",
                    "citations": [{"seg_id": real_seg_ids[0], "excerpt": segments[0].text[:40]}],
                },
            ],
            "exercises": [],
            "student_questions": [],
            "homework": [],
        }

        router = Router()
        router.register(
            MockProvider(
                {
                    seg_prompt: json.dumps(seg_payload),
                    ext_prompt: json.dumps(ext_payload),
                }
            )
        )

        report = run_raw_transcript_eval(
            raw_text,
            lesson_id="failure_test",
            router=router,
        )
        # Should detect one-topic-per-chunk failure
        has_one_per_chunk = any("Each chunk got its own topic" in f for f in report.failure_modes)
        assert has_one_per_chunk, (
            f"Expected one-topic-per-chunk failure, got: {report.failure_modes}"
        )
        # chunks_with_topics should be ~1.0
        assert report.chunks_with_topics == pytest.approx(1.0, abs=0.01)

    def test_unique_lesson_id_no_crosstalk(self) -> None:
        """Two independent calls with different lesson_ids don't interfere."""
        raw_text = _load_placeholder_text()
        router1 = _build_mock_router_for_raw(raw_text)
        router2 = _build_mock_router_for_raw(raw_text)

        report1 = run_raw_transcript_eval(
            raw_text, lesson_id="lesson_a", router=router1,
        )
        report2 = run_raw_transcript_eval(
            raw_text, lesson_id="lesson_b", router=router2,
        )

        assert report1.lesson_id == "lesson_a"
        assert report2.lesson_id == "lesson_b"
        assert report1.error is None
        assert report2.error is None


