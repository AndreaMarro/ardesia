class TestRawTranscriptEvalReportBasics:
    """RawTranscriptEvalReport construction and immutability."""

    def test_report_frozen(self) -> None:
        """Report is immutable."""
        r = RawTranscriptEvalReport(
            lesson_id="raw_test",
            groundedness_score=1.0,
            groundedness_passed=True,
            excerpt_accuracy_score=1.0,
            excerpt_accuracy_passed=True,
            total_citations=3,
            capsule=None,
            total_cost_usd=0.0,
            total_tokens=0,
            llm_calls=0,
        )
        with pytest.raises(AttributeError):
            r.groundedness_score = 0.5  # type: ignore[misc]

    def test_summary_format(self) -> None:
        """summary() returns a non-empty string."""
        r = RawTranscriptEvalReport(
            lesson_id="raw_test",
            groundedness_score=0.75,
            groundedness_passed=False,
            excerpt_accuracy_score=0.5,
            excerpt_accuracy_passed=False,
            total_citations=4,
            capsule=None,
            total_cost_usd=0.003,
            total_tokens=500,
            llm_calls=2,
            num_chunks=10,
            num_topics=3,
            num_concepts=5,
            chunks_with_topics=3.33,
            source_type="raw",
            failure_modes=("one topic per chunk",),
        )
        s = r.summary()
        assert s.startswith("[RAW-EVAL]")
        assert "groundedness=0.75" in s
        assert "chunks=10" in s
        assert "chunks/topics=3.33" in s

    def test_summary_with_error(self) -> None:
        """Summary with error shows [ERROR] prefix."""
        r = RawTranscriptEvalReport(
            lesson_id="raw_test",
            groundedness_score=0.0,
            groundedness_passed=False,
            excerpt_accuracy_score=0.0,
            excerpt_accuracy_passed=False,
            total_citations=0,
            capsule=None,
            total_cost_usd=0.0,
            total_tokens=0,
            llm_calls=0,
            error="Empty text",
        )
        s = r.summary()
        assert s == "[ERROR] raw_test: Empty text"


