class TestIngestChunkResult:
    """_ingest_chunk_result converts ChunkResult -> persisted Segments."""

    def test_empty_chunk_result_produces_no_segments(self) -> None:
        store = SQLiteStore(":memory:")
        empty = ChunkResult(items=(), source_type="raw")
        segments = _ingest_chunk_result(store, "test", empty)
        assert segments == []
        assert store.segments_for_lesson("test") == ()

    def test_raw_chunks_stored_with_zero_start_end(self) -> None:
        store = SQLiteStore(":memory:")
        result = ChunkResult(
            items=(
                ChunkResultItem(seg_id="test_s0", text="hello world"),
                ChunkResultItem(seg_id="test_s1", text="second chunk"),
            ),
            source_type="raw",
        )
        segments = _ingest_chunk_result(store, "test", result)
        assert len(segments) == 2
        for seg in segments:
            assert seg.start == 0
            assert seg.end == 0

    def test_timestamped_chunks_preserve_start_end(self) -> None:
        store = SQLiteStore(":memory:")
        result = ChunkResult(
            items=(
                ChunkResultItem(seg_id="vtt_s0", text="first", start=0, end=10),
                ChunkResultItem(seg_id="vtt_s1", text="second", start=15, end=30),
            ),
            source_type="vtt",
        )
        segments = _ingest_chunk_result(store, "test", result)
        assert segments[0].start == 0
        assert segments[0].end == 10
        assert segments[1].start == 15
        assert segments[1].end == 30

    def test_retrieve_after_ingest(self) -> None:
        store = SQLiteStore(":memory:")
        result = ChunkResult(
            items=(
                ChunkResultItem(seg_id="raw_s0", text="chunk one"),
                ChunkResultItem(seg_id="raw_s1", text="chunk two"),
            ),
            source_type="raw",
        )
        _ingest_chunk_result(store, "lesson_x", result)
        stored = store.segments_for_lesson("lesson_x")
        assert len(stored) == 2
        assert stored[0].seg_id == "raw_s0"
        assert stored[1].seg_id == "raw_s1"
        assert stored[0].text == "chunk one"
        assert stored[1].text == "chunk two"


