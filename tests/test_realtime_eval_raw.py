class TestRawTranscriptEvalEdgeCases:
    """Edge cases for raw transcript eval."""

    def test_single_word_text(self) -> None:
        """A single word produces 1 chunk and should not crash."""
        report = run_raw_transcript_eval(
            "Hello",
            lesson_id="single_word",
            router=Router(),
        )
        assert report.error is not None  # No mock router -> no LLM

    def test_no_router_raises(self, monkeypatch) -> None:
        """Without router and without any API key, raises RuntimeError."""
        import os
        import tempfile

        monkeypatch.delenv("DEEPSEEK_API_KEY", raising=False)
        monkeypatch.delenv("KIMI_API_KEY", raising=False)

        old_cwd = os.getcwd()
        with tempfile.TemporaryDirectory() as tmpdir:
            try:
                os.chdir(tmpdir)
                with pytest.raises(RuntimeError, match="DEEPSEEK_API_KEY|KIMI_API_KEY"):
                    run_raw_transcript_eval("test text", lesson_id="no_router")
            finally:
                os.chdir(old_cwd)
