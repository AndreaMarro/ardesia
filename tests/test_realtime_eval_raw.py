class TestRawTranscriptEvalWithVTT:
    """run_raw_transcript_eval with source_type='vtt'."""

    SAMPLE_VTT = """\
WEBVTT

00:00.000 --> 00:05.000
Welcome to the lesson on derivatives.

00:06.000 --> 00:12.000
The derivative measures how a function changes.

00:13.000 --> 00:20.000
We call this the rate of change.
"""

    def _build_vtt_mock_router(self, vtt_text: str, *, source_id: str = "vtt_lesson") -> Router:
        """Build a mock router with payloads grounded on VTT chunks."""
        from lessonos.ingest.chunker import chunk_vtt

        chunk_result = chunk_vtt(vtt_text, source_id=source_id)
        store = SQLiteStore(":memory:")
        _ingest_chunk_result(store, "vtt_test", chunk_result)
        segments = store.segments_for_lesson("vtt_test")
        real_seg_ids = [s.seg_id for s in segments]

        seg_prompt = build_segmentation_prompt(segments)
        ext_prompt = build_extraction_prompt(segments)

        seg_payload = [{"topic": "Derivatives intro", "seg_ids": list(real_seg_ids)}]

        first_seg = real_seg_ids[0] if real_seg_ids else "vtt_s0"
        ext_payload = {
            "concepts": [
                {
                    "name": "derivative",
                    "status": "introduced",
                    "citations": [{"seg_id": first_seg, "excerpt": segments[0].text[:30]}],
                },
            ],
            "exercises": [],
            "student_questions": [],
            "homework": [],
        }

        router = Router()
        router.register(
            MockProvider(
                {
                    seg_prompt: json.dumps(seg_payload),
                    ext_prompt: json.dumps(ext_payload),
                }
            )
        )
        return router

    def test_vtt_produces_report(self) -> None:
        """VTT input produces valid report with source_type='vtt'."""
        router = self._build_vtt_mock_router(self.SAMPLE_VTT, source_id="vtt_lesson")
        report = run_raw_transcript_eval(
            self.SAMPLE_VTT,
            lesson_id="vtt_test",
            source_id="vtt_lesson",
            source_type="vtt",
            router=router,
        )
        assert report.error is None, f"Error: {report.error}"
        assert report.num_chunks == 3  # 3 VTT cues
        assert report.source_type == "vtt"
        assert report.groundedness_score == 1.0

    def test_vtt_chunks_have_positions(self) -> None:
        """VTT chunks preserve start/end positions."""
        from lessonos.ingest.chunker import chunk_vtt

        chunk_result = chunk_vtt(self.SAMPLE_VTT)
        assert chunk_result.items[0].start == 0
        assert chunk_result.items[0].end == 5
        assert chunk_result.items[1].start == 6
        assert chunk_result.items[1].end == 12


