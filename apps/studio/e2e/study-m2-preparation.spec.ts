import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
import path from 'node:path'
const root=path.resolve(process.cwd(),'../..')
const dataDir=process.env.STUDY_DEMO_DATA_DIR??path.join(root,'.study-demo')
const access=JSON.parse(readFileSync(path.join(dataDir,'demo-access.json'),'utf8')) as {tokens:Record<string,string>}

test('M2 original draft models, one-time invitation and session revocation work on build',async({browser},info)=>{
 const tutorContext=await browser.newContext({viewport:{width:390,height:844}})
 const tutor=await tutorContext.newPage();await tutor.goto('/?vista=fisica')
 if(process.env.STUDY_EXPECTED_SHA)expect(await tutor.evaluate(()=>window.__ARDESIA_BUILD__.commitSha)).toBe(process.env.STUDY_EXPECTED_SHA)
 await tutor.getByText('Banco contenuti DRAFT — anteprima locale',{exact:true}).click()
 const bank=tutor.getByRole('region',{name:'Banco di revisione contenuti'})
 await expect(bank).toContainText('24 esercizi originali · 4 attività · 2 prove di trasferimento')
 await expect(bank).toContainText('Revisione scientifica umana: da eseguire')
 await bank.getByLabel('Attività da esplorare').selectOption('hydrostatic-v1')
 await bank.getByLabel('Profondità sotto la superficie (m)').fill('2')
 await bank.getByLabel('Pressione da calcolare').selectOption('absolute')
 await expect(bank).toContainText('Pressione assoluta: 120.945 Pa')
 await bank.getByLabel('Attività da esplorare').selectOption('buoyancy-v1')
 await bank.getByLabel('Densità del corpo (kg/m³)').fill('1200')
 await expect(bank).toContainText('nessun equilibrio libero di galleggiamento')
 await bank.getByText('24 esercizi per revisione',{exact:true}).click()
 await expect(bank.getByRole('heading',{name:'RF-01 · incontro 4',exact:true})).toBeVisible()
 await bank.getByText('Due prove di trasferimento',{exact:true}).click()
 await expect(bank.getByRole('heading',{name:'TR-B3',exact:true})).toBeVisible()
 expect(await tutor.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await tutor.screenshot({path:info.outputPath('draft-coursepack-mobile.png'),fullPage:true})
 await tutor.getByText('Accedi alla demo',{exact:true}).click();await tutor.getByLabel('Accesso sintetico',{exact:true}).fill(access.tokens['tutor-synthetic']);await tutor.getByRole('button',{name:'Accedi',exact:true}).click()
 await tutor.getByRole('button',{name:'Accessi',exact:true}).click()
 await tutor.getByLabel('Studente da invitare').selectOption('student-01')
 await tutor.getByRole('button',{name:'Crea invito monouso',exact:true}).click()
 const code=await tutor.getByLabel('Codice invito appena creato').inputValue();expect(code.length).toBeGreaterThan(20)
 const studentContext=await browser.newContext();const student=await studentContext.newPage();await student.goto('/?vista=fisica')
 await student.getByText('Accedi alla demo',{exact:true}).click();await student.getByLabel('Usa invito monouso').check();await student.getByLabel('Accesso sintetico',{exact:true}).fill(code);await student.getByRole('button',{name:'Accedi',exact:true}).click()
 await expect(student.getByRole('button',{name:'Materiali',exact:true})).toBeVisible()
 expect((await studentContext.request.post('/study/invitations/accept',{data:{token:code}})).status()).toBe(401)
 await student.getByRole('button',{name:'Revoca tutti i miei accessi',exact:true}).click()
 await expect(student.getByText('Accedi alla demo',{exact:true})).toBeVisible()
 expect((await studentContext.request.get('/study/me')).status()).toBe(401)
 await studentContext.close();await tutorContext.close()
})
