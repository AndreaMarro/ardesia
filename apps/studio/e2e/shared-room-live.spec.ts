import { expect, test, type Page } from '@playwright/test'

const base = process.env.ARDESIA_STUDIO_E2E_BASE_URL ?? 'http://127.0.0.1:5199'
test.skip(!process.env.ARDESIA_SHARED_E2E, 'Requires real room-sync service on 4318')

async function count(page: Page) {
  return page.evaluate(() => (window as any).__MAESTRO_TEST__?.apiRef.current?.getSceneElements().filter((e: any) => !e.isDeleted).length ?? 0)
}
async function draw(page: Page, x: number, y: number) {
  await page.keyboard.press('Escape')
  await page.locator('label').filter({ has: page.getByTestId('toolbar-rectangle') }).click()
  await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 100, y + 70, { steps: 4 }); await page.mouse.up()
  await page.keyboard.press('Escape')
}

test('two independent people draw, recover offline changes, keep notes private and revoke access', async ({ browser }) => {
  test.setTimeout(90_000)
  const teacher = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const student = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const a = await teacher.newPage(); const b = await student.newPage()
  const errors: string[] = []
  a.on('pageerror', e => errors.push(e.message)); b.on('pageerror', e => errors.push(e.message))
  await a.goto(base + '/#shared-live-' + Date.now())
  await expect(a.getByRole('button', { name: 'Avvia lezione condivisa' })).toBeVisible()
  await a.getByRole('button', { name: 'Avvia lezione condivisa' }).click()
  await expect(a.getByTestId('sync-status')).toHaveText('Lavagna sincronizzata')
  await a.getByRole('button', { name: 'Condivisione e appunti' }).click()
  await a.getByRole('button', { name: 'Invita a scrivere' }).click()
  const link = await a.getByRole('textbox', { name: 'Link di invito', exact: true }).inputValue()
  await a.getByRole('textbox', { name: 'Appunti personali', exact: true }).fill('NOTA PRIVATA NON TRASMESSA')
  await a.getByRole('button', { name: 'Condivisione e appunti' }).click()
  await b.goto(link)
  await expect(b.getByTestId('sync-status')).toHaveText('Lavagna sincronizzata')
  await draw(a, 380, 380)
  await expect.poll(() => count(b)).toBe(1)
  await draw(b, 650, 400)
  await expect.poll(() => count(a)).toBe(2)
  // A student's undo preserves the teacher's independent contribution.
  await expect(b.getByTestId('sync-status')).toHaveText('Lavagna sincronizzata')
  await b.keyboard.press('ControlOrMeta+Shift+Z')
  await expect.poll(() => count(a)).toBe(2)
  await b.getByRole('button', { name: 'Annulla il mio intervento' }).click()
  await expect.poll(() => count(a)).toBe(1)
  await student.setOffline(true)
  await draw(b, 500, 500)
  await expect(b.getByTestId('sync-status')).toContainText('Connessione assente', { timeout: 15_000 })
  await student.setOffline(false)
  await expect.poll(() => count(a)).toBe(2)
  await b.reload()
  await expect(b.getByTestId('sync-status')).toHaveText('Lavagna sincronizzata')
  await expect.poll(() => count(b)).toBe(2)
  await b.getByRole('button', { name: 'Condivisione e appunti' }).click()
  await expect(b.getByRole('textbox', { name: 'Appunti personali', exact: true })).toHaveValue('')
  await b.getByRole('button', { name: 'Condivisione e appunti' }).click()
  await a.screenshot({ path: '/tmp/ardesia-shared-desktop.png' })
  await a.getByRole('button', { name: 'Condivisione e appunti' }).click()
  await a.getByRole('button', { name: 'Revoca accesso 1', exact: true }).click()
  await expect(b.getByTestId('sync-status')).toContainText('Accesso revocato')
  await expect(b.getByRole('button', { name: 'Annulla il mio intervento' })).toBeDisabled()
  expect(errors).toEqual([])
  await teacher.close(); await student.close()
})

test('conflicting object edits preserve the local proposal and viewer access stays read only', async ({ browser, request }) => {
  test.setTimeout(90_000)
  const created = await (await request.post('http://127.0.0.1:4318/rooms', { data: { title: 'Conflitto controllato', clientId: 'browser-test' } })).json()
  const grant = async (role: string) => (await request.post(`http://127.0.0.1:4318/rooms/${created.roomId}/grants`, {
    headers: { Authorization: `Bearer ${created.token}` }, data: { role },
  })).json()
  const editor = await grant('editor'); const viewer = await grant('viewer')
  const link = (token: string) => `${base}/?shared=1#${created.roomId}&sync=${encodeURIComponent('http://127.0.0.1:4318')}&access=${token}`
  const ca = await browser.newContext({ viewport: { width: 1440, height: 1000 } }); const cb = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const cv = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const a = await ca.newPage(); const b = await cb.newPage(); const v = await cv.newPage()
  await a.goto(link(created.token)); await b.goto(link(editor.token))
  await expect(a.getByTestId('sync-status')).toHaveText('Lavagna sincronizzata')
  await expect(b.getByTestId('sync-status')).toHaveText('Lavagna sincronizzata')
  await draw(a, 400, 400); await expect.poll(() => count(b)).toBe(1)
  const shift = (page: Page, offset: number) => page.evaluate(delta => {
    const api = (window as any).__MAESTRO_TEST__.apiRef.current
    api.updateScene({ elements: api.getSceneElements().map((el: any) => ({ ...el, x: el.x + delta, version: el.version + 1, versionNonce: el.versionNonce + delta })) })
  }, offset)
  await ca.setOffline(true)
  await shift(a, 40)
  await expect(a.getByTestId('sync-status')).toContainText('Connessione assente', { timeout: 15_000 })
  await shift(b, 90)
  await expect(b.getByTestId('sync-status')).toHaveText('Lavagna sincronizzata')
  await ca.setOffline(false)
  await expect(a.getByTestId('sync-status')).toContainText('Lo stesso oggetto è cambiato altrove')
  const localX = await a.evaluate(() => (window as any).__MAESTRO_TEST__.apiRef.current.getSceneElements()[0].x)
  const remoteX = await b.evaluate(() => (window as any).__MAESTRO_TEST__.apiRef.current.getSceneElements()[0].x)
  expect(localX).not.toBe(remoteX)
  const download = a.waitForEvent('download')
  await a.getByRole('button', { name: 'Conserva proposta e riprendi la condivisa' }).click()
  expect((await download).suggestedFilename()).toContain('proposta-locale')
  await expect(a.getByTestId('sync-status')).toContainText(/sincronizzata|ripristinata/)
  await expect.poll(() => a.evaluate(() => (window as any).__MAESTRO_TEST__.apiRef.current.getSceneElements()[0].x)).toBe(remoteX)
  await v.goto(link(viewer.token))
  await expect(v.getByText('Puoi osservare', { exact: false })).toBeVisible()
  await expect(v.getByTestId('toolbar-rectangle')).toHaveCount(0)
  expect(await v.locator('body').evaluate(e => e.scrollWidth <= innerWidth)).toBe(true)
  await v.screenshot({ path: '/tmp/ardesia-shared-mobile.png' })
  await ca.close(); await cb.close(); await cv.close()
})
