import { describe, expect, it } from "vitest"
import { circuitConventionsLabel, circuitVerificationScope, readCircuitProof, readCircuitState } from "../toolhost/circuitCheckAdapter"
import { circuitProofEvent, circuitProofSha256 } from "../lessonos/circuitCheckEvent"
import { adaptLegacyLessonOsV1Log, assertLessonOsEnvelopePayload } from "../lessonos/eventlog"
import { circuitStudyEvidence } from "../lessonos/circuitStudyEvidence"
import { buildCircuitCheckInsert } from "../toolhost/ToolCanvasEmbeddable"
import { EMBED_DATA_KEY } from "../toolhost/caps/board"
import portResponse from "./fixtures/circuitcheck-port-response.json"
import acResponse from "./fixtures/circuitcheck-ac-response.json"
import powerResponse from "./fixtures/circuitcheck-power-response.json"
// Generated by canonical create_lesson: public floating V-source circuit, no private source.
import impedanceResponse from "./fixtures/circuitcheck-ac-port-response.json"

const verification = {
  electrical_claim:"PHASOR_PORT_PATHS_CROSSCHECKED",backend:"PHASOR_PORT_RESIDUALS_CHECKED",
  lesson:"phasor-port-crosscheck",product_verified:false,
  checks:["legge dei nodi","legge delle maglie","identità di Tellegen","leggi costitutive di tutti i componenti",
    "sorgenti indipendenti spente e corrente di prova orientata","impedenza di porta: rapporto tensione/corrente",
    "misura di porta confrontata con il kernel"],
}

describe("scope impedenza AC e compatibilità storica", () => {
  it("accetta solo la tupla completa e ordinata dei controlli di porta AC", () => {
    expect(circuitVerificationScope(verification)).toBe("phasor_port_crosschecked")
    for(const value of [
      {...verification,electrical_claim:"VERIFIED"}, {...verification,backend:"CLOSED"},
      {...verification,lesson:"phasor-all-branches-crosscheck"}, {...verification,product_verified:true},
      {...verification,checks:verification.checks.slice(0,4)},
      {...verification,checks:[...verification.checks].reverse()},
    ]) expect(circuitVerificationScope(value)).toBeNull()
  })

  it("l’evento canonico conserva lo scope additivo con la propria revisione", () => {
    const payload={exerciseId:"circuit:a",circuitFingerprint:"a".repeat(64),embedId:"board:a",
      answerExact:"2 + j3",unit:"Ω",engineRevision:"b".repeat(40),labels:{it:"Impedenza"},
      verificationScope:"phasor_port_crosschecked",lessonBuild:"c".repeat(64),proofSha256:"d".repeat(64)}
    expect(()=>assertLessonOsEnvelopePayload("circuit.proof.verified",payload)).not.toThrow()
    for(const extra of [{verificationScope:"impedance_verified"},{lessonBuild:"wrong"},{proofSha256:"wrong"}]) {
      expect(()=>assertLessonOsEnvelopePayload("circuit.proof.verified",{...payload,...extra})).toThrow()
    }
    const {lessonBuild:_,...incomplete}=payload
    expect(()=>assertLessonOsEnvelopePayload("circuit.proof.verified",incomplete)).toThrow(/scope CircuitCheck/)
  })

  it("mantiene i tre digest catturati prima dell’aggiunta dello scope", async () => {
    // Frozen before this patch from actual historical fixture payloads and adapter.
    const entries = [
      [portResponse,"177d57fdbc8a217140856b787a49ff20e4c708c92db84432bad18912e2b0a365"],
      [acResponse,"478969cd4002dc37209e2db50e350792815298e8d32e2370f824274450314bc5"],
      [powerResponse,"a1007c1266dad8dd1cdd284cbeaf87a0ed5b43106515f96c893cad0c70bbd414"],
    ] as const
    for(const [payload,digest] of entries) {
      expect(await circuitProofSha256(readCircuitProof(payload,payload.netlist))).toBe(digest)
    }
  })

  it("conserva coordinate, AST e trasformazione della risposta reale nel quaderno", () => {
    const proof=readCircuitProof(impedanceResponse,impedanceResponse.netlist)
    expect(proof.scope).toBe("phasor_port_crosschecked")
    expect(proof.answer.quantity).toBe("equivalent_impedance")
    expect(proof.answer.complex_impedance).toEqual(impedanceResponse.answer.complex_impedance)
    expect(proof.answer.math).toEqual(impedanceResponse.answer.math)
    expect(proof.answer.phasor).toBeUndefined()
    expect(proof.answer.complex_power).toBeUndefined()
    expect(proof.portAnalysis).toEqual(impedanceResponse.port_analysis)
    expect(proof.conventions).toEqual(impedanceResponse.conventions)
    expect(proof.verification?.product_verified).toBe(false)
    expect(circuitConventionsLabel(proof)).toContain("Impedenza fra p e 0")
    expect(circuitConventionsLabel(proof)).toContain("non dipende da RMS o picco")
    const selectedStep=proof.steps.findIndex(step=>step.focus?.includes(proof.portAnalysis!.test_source.id))
    const state={kind:"circuitcheck-proof-v1",netlist:proof.netlist,method:"test_current",proof,
      selectedStep,selectedFocus:proof.portAnalysis!.test_source.id,trace:[],diagnosis:null}
    const restored=readCircuitState(JSON.parse(JSON.stringify(state)))
    expect(restored.proof).toEqual(proof)
    expect(restored.selectedFocus).toBe(proof.portAnalysis!.test_source.id)
    expect(restored.selectedStep).toBe(selectedStep)
  })

  it("rifiuta metadati di porta incompatibili con ingresso, verso o scala di prova", () => {
    const p=impedanceResponse.port_analysis
    const badPorts=[undefined,{...p,schema:"wrong"},{...p,port:["0","p"]},{...p,port:["p","p"]},
      {...p,test_source:{...p.test_source,id:"R1"}},
      {...p,test_source:{...p.test_source,terminals:["p","0"]}},
      {...p,test_source:{...p.test_source,current:{...p.test_source.current,exact:"2"}}},
      {...p,test_source:{...p.test_source,current:{...p.test_source.current,unit:"V"}}},
      {...p,test_source:{...p.test_source,current:{...p.test_source.current,phase_degrees:180}}},
      {...p,deactivated_sources:[]},{...p,deactivated_sources:["I1","V1"]},
      {...p,status:"VERIFIED"},{...p,canonical_proof:true}]
    for(const port_analysis of badPorts) {
      expect(()=>readCircuitProof({...impedanceResponse,port_analysis},impedanceResponse.netlist)).toThrow()
    }
    for(const conventions of [undefined,{...impedanceResponse.conventions,power_calculated:true},
      {...impedanceResponse.conventions,impedance_definition:undefined},
      {...impedanceResponse.conventions,test_current:"first → second"},
      {...impedanceResponse.conventions,impedance_amplitude_invariant:false}]) {
      expect(()=>readCircuitProof({...impedanceResponse,conventions},impedanceResponse.netlist)).toThrow()
    }
    for(const answer of [
      {...impedanceResponse.answer,quantity:"power"},{...impedanceResponse.answer,unit:"V"},
      {...impedanceResponse.answer,reference:"0 → p"},{...impedanceResponse.answer,math:undefined},
      {...impedanceResponse.answer,phasor:acResponse.answer.phasor},
      {...impedanceResponse.answer,complex_power:powerResponse.answer.complex_power},
      {...impedanceResponse.answer,complex_impedance:{...impedanceResponse.answer.complex_impedance,coefficients:["9","0","0","0"]}},
    ]) expect(()=>readCircuitProof({...impedanceResponse,answer},impedanceResponse.netlist)).toThrow()
    for(const v of [portResponse.verification,acResponse.verification,powerResponse.verification]) {
      expect(()=>readCircuitProof({...impedanceResponse,verification:v},impedanceResponse.netlist)).toThrow()
    }
  })

  it("firma i campi aggiunti e ritrova soltanto la prova che coincide con l’evento", async () => {
    const proof=readCircuitProof(impedanceResponse,impedanceResponse.netlist)
    const inserted=buildCircuitCheckInsert([])!
    const sceneFor=(candidate:unknown)=>JSON.stringify({elements:[{...inserted.embed,customData:{
      [EMBED_DATA_KEY]:{owner:"io.ardesia.circuit-reasoning",state:{kind:"circuitcheck-proof-v1",
        netlist:proof.netlist,method:"test_current",proof:candidate,selectedStep:0,trace:[],diagnosis:null}},
    }}]})
    const event=await circuitProofEvent(proof,inserted.embedId,1000)
    const events=[{...event,seq:1}]
    const envelope=adaptLegacyLessonOsV1Log(events[0]!,{lessonId:"ac-port-lesson",
      sessionId:"11111111-1111-4111-8111-111111111111",eventId:"70000000-0000-4000-8000-000000000001",
      actor:{type:"teacher",id:"test"},producer:{id:"test.ac-port",version:"1.0.0",commitSha:"a".repeat(40)},idempotencyKey:null})
    expect(envelope.payload.verificationScope).toBe("phasor_port_crosschecked")
    expect((await circuitStudyEvidence(sceneFor(proof),events))[0]?.proof).toEqual(proof)
    const coordinates=proof.answer.complex_impedance!
    const port=proof.portAnalysis!
    for(const complex_impedance of [
      {...coordinates,real_exact:"3"},{...coordinates,imaginary_exact:"-7"},
      {...coordinates,real_decimal:"2.1"},{...coordinates,imaginary_decimal:"-0.1"},
      {...coordinates,coefficients:["3","0","0","-7"]},
      {...coordinates,decimal_precision:{...coordinates.decimal_precision!,real:64}},
    ]) expect(await circuitStudyEvidence(sceneFor({...proof,answer:{...proof.answer,complex_impedance}}),events)).toEqual([])
    for(const portAnalysis of [
      undefined,{...port,test_source:{...port.test_source,id:"I_changed_probe"}},
      {...port,test_source:{...port.test_source,current:{...port.test_source.current,exact:"2"}}},
      {...port,deactivated_sources:["V1"]},{...port,canonical_proof:true},
    ]) expect(await circuitStudyEvidence(sceneFor({...proof,portAnalysis}),events)).toEqual([])
    const changedConventions={...proof,conventions:{...proof.conventions!,omega:{exact:"3",unit:"rad/s"}}}
    expect(await circuitStudyEvidence(sceneFor(changedConventions),events)).toEqual([])
    const wrongScope=events.map(item=>item.kind === "circuit.proof.verified" ? {...item,verificationScope:"electrical_result" as const} : item)
    expect(await circuitStudyEvidence(sceneFor(proof),wrongScope)).toEqual([])
    const state={kind:"circuitcheck-proof-v1",netlist:proof.netlist,method:"test_current",
      proof:{...proof,schema:"circuit-proof.v1",verification:null},selectedStep:0,trace:[],diagnosis:null}
    const historical=readCircuitState(state).proof!
    expect(historical.scope).toBe("legacy_unrecorded")
    expect(historical.verification).toBeNull()
    await expect(circuitProofEvent(historical,inserted.embedId,1000)).rejects.toThrow(/scope/)
  })
})
