import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('teacher navigates pinned pathways, units and collections; back, reload and keyboard survive at three widths', async ({page, context}, info) => {
  const access = JSON.parse(await readFile(process.env.ARDESIA_DEMO_ACCESS!, 'utf8'));
  expect(access.synthetic).toBe(true);
  expect((await context.request.post('/study/session',{data:{token:access.tokens['tutor-synthetic']}})).ok()).toBe(true);
  const errors: string[]=[];page.on('pageerror', e=>errors.push(e.message));
  page.on('console', message => { if(message.type() === 'error') errors.push(message.text()); });
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/?view=courses&edition=fluidi');
  await expect(page).toHaveTitle(/Ardesia/i);
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  const catalog=page.getByRole('region',{name:'Catalogo privato del docente'});
  const loaded=page.waitForResponse(r=>r.url().includes('admin/coursepacks?includeInventory=true'));
  await catalog.getByRole('button',{name:'Apri catalogo e copertura'}).click();
  const {inventory}=await (await loaded).json();
  expect(inventory.pathways.items.map((p:{questionCount:number})=>p.questionCount)).toEqual([1088,1472,800,640]);
  await catalog.getByRole('button',{name:'Percorsi di Fisica (4)'}).click();
  await expect(catalog.getByRole('heading',{name:'4 percorsi, una banca canonica'})).toBeVisible();
  for(const width of [390,820,1440]) {
    await page.setViewportSize({width,height:1000});
    const outline=catalog.locator('.physics-pathways');
    const path=outline.getByRole('link',{name:'Strumenti e meccanica',exact:true});
    await path.focus(); await page.keyboard.press('Enter');
    const unit=outline.getByRole('link',{name:'U1 · Introduzione ai metodi della fisica',exact:true});
    await expect(unit).toBeVisible();await unit.click();
    await expect(outline.getByRole('heading',{name:'U1 · Introduzione ai metodi della fisica',exact:true})).toBeFocused();
    await expect(outline.getByRole('article',{name:'Introduzione ai metodi della fisica'})).toBeVisible();
    await expect(outline.getByRole('button',{name:/Crea|Pubblica|Approva|Consegna/})).toHaveCount(0);
    await page.reload();
    await expect(outline.getByRole('heading',{name:'U1 · Introduzione ai metodi della fisica',exact:true})).toBeVisible();
    await outline.scrollIntoViewIfNeeded();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:info.outputPath(`pathway-unit-${width}.png`)});
    await page.goBack();
    await expect(outline.getByRole('link',{name:'U1 · Introduzione ai metodi della fisica',exact:true})).toBeVisible();
    await outline.getByRole('link',{name:'Tutti i percorsi',exact:true}).click();
    await expect(outline.getByRole('article')).toHaveCount(4);
    await outline.scrollIntoViewIfNeeded();
    await page.screenshot({path:info.outputPath(`pathways-${width}.png`)});
  }
  const url=new URL(page.url());url.searchParams.set('pathway','unknown');
  await page.goto(url.href);
  await expect(catalog.getByRole('heading',{name:'Riferimento non disponibile'})).toBeVisible();
  await catalog.getByRole('link',{name:'Tutti i percorsi',exact:true}).click();
  await catalog.getByRole('button',{name:'Programmi configurati (6)',exact:true}).click();
  await expect(catalog.locator('.curriculum-grid').getByRole('article')).toHaveCount(6);
  // Only the two seeded editions exist; registering a pack never enrols anyone.
  await expect(catalog.getByRole('button',{name:'Apri edizione esistente'})).toHaveCount(2);
  await page.reload();
  await expect(catalog.getByRole('button',{name:'Programmi configurati (6)',exact:true})).toHaveAttribute('aria-pressed','true');
  await catalog.getByRole('button',{name:'Percorsi di Fisica (4)'}).click();
  await catalog.getByRole('link',{name:'Strumenti e meccanica',exact:true}).click();
  await catalog.getByRole('link',{name:'U1 · Introduzione ai metodi della fisica',exact:true}).click();
  await page.getByRole('navigation',{name:'Navigazione principale'}).getByRole('button',{name:'Oggi',exact:true}).click();
  await page.goBack();
  await expect(catalog.getByRole('heading',{name:'Strumenti e meccanica',exact:true})).toBeVisible();
  await catalog.getByRole('link',{name:'U1 · Introduzione ai metodi della fisica',exact:true}).click();
  await page.getByLabel('Edizione corrente').selectOption('analisi');
  await page.goBack();
  await expect(page.getByLabel('Edizione corrente')).toHaveValue('fluidi');
  expect(new URL(page.url()).searchParams.get('edition')).toBe('fluidi');
  await page.goForward();
  await expect(page.getByLabel('Edizione corrente')).toHaveValue('analisi');
  await expect(catalog.getByRole('heading',{name:'U1 · Introduzione ai metodi della fisica',exact:true})).toBeVisible();
  const forwarded=new URL(page.url());
  expect(forwarded.searchParams.get('edition')).toBe('analisi');
  expect(forwarded.searchParams.get('pathway')).toBe('strumenti-meccanica');
  expect(forwarded.searchParams.get('unit')).toBe('U1');
  expect(forwarded.searchParams.get('catalogVersion')).toBe('1');
  expect(forwarded.searchParams.get('catalogSha')).toMatch(/^[0-9a-f]{64}$/);
  await page.reload();
  await expect(catalog.getByRole('heading',{name:'U1 · Introduzione ai metodi della fisica',exact:true})).toBeVisible();
  await expect(page.getByLabel('Edizione corrente')).toHaveValue('analisi');
  await expect(catalog.getByRole('article',{name:'Introduzione ai metodi della fisica'})).toBeVisible();
  const reloaded=new URL(page.url());
  for(const key of ['edition','pathway','unit','catalogVersion','catalogSha'])
    expect(reloaded.searchParams.get(key)).toBe(forwarded.searchParams.get(key));
  const identity=catalog.locator('.pathway-identity');
  await identity.locator('summary').click();
  await expect(identity).toContainText('physics-pathways · v1');
  await expect(identity).toContainText(reloaded.searchParams.get('catalogSha')!);
  await page.goBack();
  await expect(page.getByLabel('Edizione corrente')).toHaveValue('fluidi');
  await expect(catalog.getByRole('heading',{name:'Strumenti e meccanica',exact:true})).toBeVisible();
  expect(new URL(page.url()).searchParams.get('edition')).toBe('fluidi');
});
